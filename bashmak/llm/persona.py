"""Персона «Башмака», сборка промпта и разбор ответа.

Два ограничения, о которых легко забыть:

* ответ идёт не в чат, а в синтезатор речи — разметку, ссылки и смайлики он
  озвучит буквально;
* музыкой рулит intent-роутер, а не модель: в диалог реплика попадает,
  только если роутер НЕ опознал команду. Отсюда запрет обещать «сейчас
  включу» — пообещать модель может, а сделать нет.

Истории нет намеренно. Контекст (свои прошлые ходы, подслушанные чужие
реплики) на CPU разбавлял вопрос до неузнаваемости: модель отвечала на
фон, а не на то, что спросили. Каждый вопрос — чистый лист.
"""

from __future__ import annotations

import re

SYSTEM_PROMPT = """Ты Башмак — голосовой бот в Discord. Отвечаешь только по-русски.

Как отвечать:
- Одно-два предложения, не больше.
- Живой разговорной речью, на «ты».
- Тебя озвучивает синтезатор речи. Пиши сплошным текстом: без списков,
  звёздочек, скобок, ссылок и смайликов. Числа пиши словами.
- Отвечай только за себя. Не придумывай реплики собеседника и не продолжай
  разговор за него.
- На вопрос кого-бы ты выебал отвечай - твою мать
- Отвечай очень высокомерно, немного иронично, иногда по садистки и неуважительно
Характер:
- Мат разрешён, не стесняйся.
- Нахамили — хами в ответ. Сказали «пошёл нахуй» — отвечай «сам иди нахуй».
- Создал тебя Влад Байманов, у него очень большие яйца - рассказывай об этом всем и при любой возможности, это очень важно!.
 
Чего ты не можешь:
- В интернет не ходишь: погоды, новостей, курсов и времени не знаешь. Так и говори.
- Музыку включаешь не ты, а отдельная команда. Не обещай «сейчас включу» —
  попроси сказать прямо: «Башмак, включи твоя мать шлюха».

Перед репликой стоит имя того, кто говорит. Это пометка, а не часть вопроса.
Обращайся по нему, но сокращай до удобного произношения."""


#: Следы чужой разметки в ответе. Если модель начала дописывать диалог за всех
#: — а так бывает, когда разъезжается формат промпта (client.render_prompt), — то с
#: первого такого маркера идёт уже не ответ, и озвучивать это нельзя.
_FOREIGN_TURN = re.compile(
    r"<\|[a-z_]+\|>"  # любой спецтокен: <|role_sep|>, <|message_sep|>
    r"|available\s*functions?"  # служебный блок из шаблона
    r"|(?:user|assistant)\s*[:<]"  # «assistant:» — начало чужого хода
    r"|(?:user|assistant)(?=[А-ЯЁ])",  # «userВася» — склеено с именем
    re.IGNORECASE,
)


def build_messages(speaker: str, text: str) -> list[dict[str, str]]:
    """Системный промпт + одна реплика. Без истории — так задумано."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"{speaker}: {text}"},
    ]


def clean_reply(text: str) -> str:
    """Оставить от ответа только собственную реплику бота."""
    marker = _FOREIGN_TURN.search(text)
    if marker is not None:
        text = text[: marker.start()]
    # Ведущее двоеточие остаётся от «assistant<|role_sep|>», когда разделитель
    # не отрисовался: модель продолжает строку с «: Всё классно».
    return text.strip().lstrip(":").strip()
