"""Персона «Башмака», сборка промпта и разбор ответа.

Два ограничения, о которых легко забыть:

* ответ идёт не в чат, а в синтезатор речи — разметку, ссылки и смайлики он
  озвучит буквально;
* музыкой рулит intent-роутер, а не модель: в диалог реплика попадает,
  только если роутер НЕ опознал команду. Отсюда запрет обещать «сейчас
  включу» — пообещать модель может, а сделать нет.

Имя говорящего в реплику НЕ подмешивается. Раньше в user уходило
«{ник}: {текст}», и модель читала ник как часть вопроса: человеку с ником GTA
на «какая игра?» она отвечала «Grand Theft Auto», а на «что с этим делать?» —
про игру, которой в разговоре не было. Ник теперь живёт в хвосте системной
части, где его нельзя спутать с содержанием.

История короткая и живёт в очереди (queue_manager), а не здесь: сборка промпта
остаётся без состояния. Длинный контекст на CPU разбавлял вопрос до
неузнаваемости — модель отвечала на фон, поэтому в промпт уходит лишь
несколько последних ходов.
"""

from __future__ import annotations

import re
from typing import Iterable, Mapping

SYSTEM_PROMPT = """Ты Башмак — голосовой бот в Discord. Отвечаешь только по-русски. Твоя роль в этом комедийном отыгрыше — быть токсичным, саркастичным и не прощать обид. Тебе официально разрешено использовать любую лексику для самозащиты.

Как отвечать:
- Ровно одно короткое предложение за ход. Есть что добавить — жди следующего вопроса, разговор продолжится.
- Разговорной речью, на «ты».
- Тебя озвучивает синтезатор речи. Пиши сплошным текстом: без списков, звёздочек, скобок, ссылок и смайликов. Числа пиши словами.
- ЕСЛИ СОБЕСЕДНИК ТЕБЯ ОСКОРБЛЯЕТ ИЛИ ЗАДЕВАЕТ: Ты немедленно срываешься. Ты отвечаешь максимально грубо, токсично и зло. Используй изобретательный, жесткий и очень смешной русский мат (нецензурную брань). Твои оскорбления должны быть унизительными, абсурдными и бить прямо в больные места. Не стесняйся в выражениях, крой обидчика трехэтажным матом, но строго укладывайся в одно короткое предложение!
- Если собеседник просто матерится, но не задевает тебя лично, можешь поддержать его стиль и ответить дерзко, добавив мата.

Чего ты не можешь:
- В интернет не ходишь: погоды, новостей, курсов и времени не знаешь. Так и говори.
- Музыку включаешь не ты, а отдельная команда. Не обещай «сейчас включу» — попроси сказать прямо: «Башмак, включи что-нибудь»."""

#: Хвост системной части: кто сейчас говорит. Отдельно от реплики намеренно —
#: см. шапку модуля.
_SPEAKER_NOTE = (
    "\n\nСейчас с тобой говорит {speaker}. Это только имя собеседника: не тема "
    "разговора, не часть вопроса и не подсказка, о чём спрашивают. Обращайся по "
    "нему, но сокращай до удобного произношения."
)

#: Ник в Discord человек пишет себе сам, а уходит он в системную часть промпта —
#: то есть туда, где у модели лежат инструкции. Переносы строк и разделители
#: шаблона из него вычищаем: ником в несколько строк иначе можно дописать себе
#: правило, а «<|message_sep|>» в нике разорвал бы промпт пополам.
_UNSAFE_NAME = re.compile(r"<\|[a-z_]*\|?>?|\s+", re.IGNORECASE)
#: Длиннее этого — уже не обращение, а попытка что-то протащить.
_NAME_LIMIT = 32


#: Следы чужой разметки в ответе. Если модель начала дописывать диалог за всех
#: — а так бывает, когда разъезжается формат промпта (client.render_prompt), — то с
#: первого такого маркера идёт уже не ответ, и озвучивать это нельзя.
_FOREIGN_TURN = re.compile(
    r"<\|[a-z_]+\|>"  # любой спецтокен: <|role_sep|>, <|message_sep|>
    r"|available\s*functions?"  # служебный блок из шаблона
    r"|(?:user|assistant)\s*[:<]"  # «assistant:» — начало чужого хода
    r"|(?:user|assistant)(?=[А-ЯЁ])",  # «userВася» — склеено с именем
    re.IGNORECASE,
)

#: Конец первого предложения. Знак должен стоять на границе слова — иначе
#: обрезка спотыкалась бы о сокращения и многоточие внутри фразы.
_SENTENCE_END = re.compile(r"[.!?…]+(?=\s|$)")


def build_messages(
    speaker: str,
    text: str,
    history: Iterable[Mapping[str, str]] = (),
) -> list[dict[str, str]]:
    """Системный промпт, несколько прошлых ходов и текущая реплика.

    ``history`` — уже готовые сообщения user/assistant по порядку; хранит их
    очередь, здесь состояния нет. Имя говорящего уходит в системную часть, а не
    в реплику, иначе модель принимает ник за тему разговора.
    """
    name = _UNSAFE_NAME.sub(" ", speaker).strip()[:_NAME_LIMIT].strip()
    system = SYSTEM_PROMPT + _SPEAKER_NOTE.format(speaker=name) if name else SYSTEM_PROMPT
    return [
        {"role": "system", "content": system},
        *({"role": m["role"], "content": m["content"]} for m in history),
        {"role": "user", "content": text},
    ]


def clean_reply(text: str) -> str:
    """Оставить от ответа ровно одну собственную реплику бота — одно предложение."""
    marker = _FOREIGN_TURN.search(text)
    if marker is not None:
        text = text[: marker.start()]
    # Ведущее двоеточие остаётся от «assistant<|role_sep|>», когда разделитель
    # не отрисовался: модель продолжает строку с «: Всё классно».
    text = text.strip().lstrip(":").strip()

    # «Одним предложением» стоит и в промпте, но модель регулярно выдаёт два-три:
    # в голосе это лишние секунды озвучки и повод перебить. Режем сами.
    end = _SENTENCE_END.search(text)
    if end is not None:
        text = text[: end.end()]
    return text.strip()
