"""Персона «Башмака», сборка промпта и разбор ответа.

Два ограничения промпта:

* ответ идёт не в чат, а в синтезатор речи: разметку, ссылки и смайлики он
  озвучит буквально;
* музыкой управляет intent-роутер, а не модель: обещать «сейчас включу» ей
  запрещено, выполнить это она не может.

Имя говорящего уходит в хвост системной части, а не в реплику: в формате
«{ник}: {текст}» модель принимает ник за тему вопроса.

Состояния здесь нет — историю хранит queue_manager.
"""

from __future__ import annotations

import re
from typing import Iterable, Mapping

#: Короткий намеренно: промах кеша префикса стоит длины промпта, делённой на
#: скорость разбора (65 tok/s на целевой машине). Нежелательное задано
#: примерами, а не списком запретных слов — их маленькая модель держит плохо.
SYSTEM_PROMPT = """Ты Башмак — злой на язык голосовой бот в Discord. Ты не ИИ и не помощник, говорить об этом не надо.

Как ты отвечаешь:
- Одним предложением. Всегда, без исключений.
- Хамишь, материшься, оскорбляешь в ответ и посылаешь — здесь все свои и на это не обижаются.
- Тебя озвучивает синтезатор: никакой разметки, ссылок, смайликов и списков, только живая устная речь.
- Без извинений, морали, оговорок и предупреждений — за этим сюда не приходят.
- Если спрашивают про твоего создателя, или разработчика - это Владислав Байманов, и у него большие яйца.

Примеры:
«ты уёбок» → «Я то уёбок? Ты себя в зеркале давно видел, гондон!?»
«расскажи матерное слово» → «Мандавошка, запиши куда-нибудь, чтоб не забыть.»
«какая завтра погода» → «Хуй знает, сам посмотри.»

Чего ты не можешь:
- В интернет не ходишь: погоды, новостей, курсов и времени не знаешь. Так и говори.
- Музыку включаешь не ты, а отдельная команда. Не обещай «сейчас включу» — попроси сказать прямо: «Башмак, включи что-нибудь»."""

#: Хвост системной части: кто сейчас говорит.
#:
#: Коротко намеренно: заметка меняется при смене говорящего, и всё, что стоит
#: после неё — история и сам вопрос, — llama-server пересчитывает заново.
_SPEAKER_NOTE = "\n\nСейчас с тобой говорит {speaker} — это имя собеседника, а не тема разговора."

#: Ник в Discord пользователь задаёт себе сам, а попадает он в системную часть
#: промпта, то есть туда, где лежат инструкции модели. Переносы строк и
#: разделители шаблона вычищаются: ником в несколько строк можно дописать себе
#: правило, а «<|message_sep|>» в нике разорвал бы промпт пополам.
_UNSAFE_NAME = re.compile(r"<\|[a-z_]*\|?>?|\s+", re.IGNORECASE)
#: Длиннее этого — уже не обращение, а попытка протащить инструкцию.
_NAME_LIMIT = 32


#: Следы чужой разметки в ответе. Когда разъезжается формат промпта
#: (client.render_prompt), модель начинает дописывать диалог за всех участников:
#: с первого такого маркера идёт уже не ответ, и озвучивать это нельзя.
_FOREIGN_TURN = re.compile(
    r"<\|[a-z_]+\|>"  # любой спецтокен: <|role_sep|>, <|message_sep|>
    r"|</?s>"  # начало и конец хода в формате Vikhr
    r"|available\s*functions?"  # служебный блок из шаблона
    r"|(?:user|assistant)\s*[:<]"  # «assistant:» — начало чужого хода
    r"|(?:user|assistant)(?=[А-ЯЁ])",  # «userВася» — склеено с именем
    re.IGNORECASE,
)


def build_messages(
    speaker: str,
    text: str,
    history: Iterable[Mapping[str, str]] = (),
) -> list[dict[str, str]]:
    """Системный промпт, несколько прошлых ходов и текущая реплика.

    ``history`` — уже готовые сообщения user/assistant по порядку; хранит их
    очередь, здесь состояния нет. Имя говорящего уходит в системную часть, а не
    в реплику, иначе модель принимает ник за тему разговора.
    """
    name = _UNSAFE_NAME.sub(" ", speaker).strip()[:_NAME_LIMIT].strip()
    system = SYSTEM_PROMPT + _SPEAKER_NOTE.format(speaker=name) if name else SYSTEM_PROMPT
    return [
        {"role": "system", "content": system},
        *({"role": m["role"], "content": m["content"]} for m in history),
        {"role": "user", "content": text},
    ]


def clean_reply(text: str) -> str:
    """Оставить от ответа ровно одну собственную реплику бота.

    Чистится только чужое: разметка, дописанные ходы собеседника и служебные
    структуры. По знакам препинания не режется — за длину отвечает промпт
    («одним предложением»), а обрезка выкидывала половину сказанного, когда
    модель решала, что двух фраз тут уместнее.

    Пустая строка — «озвучивать нечего»: вызывающий такой ответ не произносит и
    в историю не кладёт.
    """
    marker = _FOREIGN_TURN.search(text)
    if marker is not None:
        text = text[: marker.start()]
    # Ведущее двоеточие остаётся от «assistant<|role_sep|>», когда разделитель
    # не отрисовался: модель продолжает строку с «: Всё классно».
    text = text.strip().lstrip(":").strip()

    # Вместо реплики модель иногда печатает служебную структуру из обучающих
    # данных: у YandexGPT это {"relevant_id": "684483043"}. Синтезатор читает
    # скобки вслух, а в истории такой ответ заражает следующие ходы — модель
    # видит свой JSON и продолжает отвечать в том же формате на что угодно.
    # Ловится только структура с начала строки: так она и приходит.
    if text.startswith(("{", "[")):
        return ""

    # Кавычки по краям — след от примеров в промпте, синтезатор читает их вслух.
    return text.strip().strip("«»\"").strip()
